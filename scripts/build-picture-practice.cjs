"use strict";
/* Read only unsigned picture questions from the independently generated lesson JSON.
 * Output is a static classic script, never a network fetch or an approved chapter. */
const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict");
const root=path.resolve(__dirname,"..");
function compile(){
 const lessons=[];
 for(let n=1;n<=8;n++){
  const chapter="b01-c"+String(n).padStart(3,"0");
  const src=JSON.parse(fs.readFileSync(path.join(root,"lessons/b01/c"+String(n).padStart(3,"0")+".json"),"utf8"));
  assert.equal(src.status,"draft","Cannot silently publish an unsigned pilot chapter");
  const exercises=src.exercises.filter(ex=>ex.type==="pic");
  assert(exercises.length>0,"No picture exercises for "+chapter);
  for(const item of exercises){
   assert.equal(item.status,"proposed_ungraded");
   assert.equal(item.scoring_enabled,false);
   assert.equal(item.review?.by,null);
  }
  lessons.push({id:chapter,chapter:n,title:src.manuscript_title,status:"draft",exercises});
 }
 return {schema:"tablinum-picture-practice-v1",published:false,reviewed:false,chapters:lessons};
}
function output(){return "/* Generated by scripts/build-picture-practice.cjs; original Latin picture prompts are unsigned. */\n"+
 "globalThis.TablinumPicturePracticeData="+JSON.stringify(compile(),null,2).replace(/</g,"\\u003c")+";\n"}
function main(){
 const out=path.join(root,"content/picture-exercises.js"),source=output();
 if(process.argv.includes("--check")){
  assert.equal(fs.readFileSync(out,"utf8"),source,"Picture practice compilation stale; run node scripts/build-picture-practice.cjs");
  console.log("PASS: unsigned picture-practice classic script matches manuscript-derived JSON exactly");
 }else{fs.writeFileSync(out,source);console.log("BUILT: content/picture-exercises.js (ungraded, standalone, offline)")}
}
if(require.main===module)main();
module.exports={compile,output};
