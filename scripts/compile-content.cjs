"use strict";
/** Offline, dependency-free Phase 2 compiler. Phase 3 alone may load compiled scripts into UI.
 * No candidate->approved promotion and no automatic signing are permitted. */
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {addId,expectedCourseId,fnv32}=require('./lib/ids.cjs');
const {checkTokens,morphKey}=require('./lib/tokens.cjs');
const {checkGrammar,normalizeMorph}=require('./lib/grammar.cjs');
const {checkPilot}=require('./lib/pilot-grammar.cjs');
const {checkForm}=require('./lib/paradigms.cjs');
const {checkCoverage}=require('./lib/coverage.cjs');
const {recurrenceReport}=require('./lib/recurrence.cjs');
const {validateRegistry,validDate}=require('./lib/schema.cjs');
const {extractLessons,extractArray,readLegacySource}=require('./lib/extract-legacy.cjs');
const ROOT=path.resolve(__dirname,'..');
const json=v=>JSON.stringify(v,null,2)+'\n';
const sha=s=>crypto.createHash('sha256').update(s).digest('hex');
const jsLiteral=value=>JSON.stringify(value).replace(/</g,'\\u003c').replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029');
const outScript=(key,value)=>`/* Generated by scripts/compile-content.cjs. Do not edit. */\n(globalThis.TablinumCompiledContent ||= {})[${JSON.stringify(key)}]=${jsLiteral(value)};\n`;
function listing(dir){if(!fs.existsSync(dir))return [];return fs.readdirSync(dir,{withFileTypes:true}).sort((a,b)=>a.name.localeCompare(b.name,'en')).flatMap(e=>e.isDirectory()?listing(path.join(dir,e.name)):e.isFile()&&e.name.endsWith('.json')?[path.join(dir,e.name)]:[])}
function must(b,message){if(!b)throw Error(message)}
function courseStatus(l){return ['draft','latin_reviewed','audio_ready','approved'].includes(l.status)}
function compile(opts={}){
 const root=opts.root||ROOT;
 const plan=opts.plan||JSON.parse(fs.readFileSync(path.join(root,'curriculum/vocabulary-budgets-130.json'),'utf8'));
 const grammar=opts.grammar||JSON.parse(fs.readFileSync(path.join(root,'curriculum/grammar-features.json'),'utf8'));
 const retired=opts.retired||JSON.parse(fs.readFileSync(path.join(root,'curriculum/retired-ids.json'),'utf8'));
 const oldLedger=opts.ledger||JSON.parse(fs.readFileSync(path.join(root,'curriculum/vocabulary-introductions-130.json'),'utf8'));
 const reg=opts.registry||JSON.parse(fs.readFileSync(path.join(root,'curriculum/lexicon/lexemes.json'),'utf8'));
 const regMap=validateRegistry(reg);
 must(grammar.schema==='tablinum.strict-grammar-features.v1'&&Array.isArray(grammar.features)&&grammar.features.length>=120,'strict grammar feature schema invalid');
 must(retired.schema==='tablinum-retired-ids-v1'&&Array.isArray(retired.ids),'retired IDs schema invalid');
 const featureSignatures=new Set();
 for(const f of grammar.features){
  must(typeof f.id==='string'&&/^[a-z][a-z0-9.]+$/.test(f.id),'invalid grammar ID '+f.id);
  must(f.first_chapter===null||(Number.isInteger(f.first_chapter)&&f.first_chapter>=1&&f.first_chapter<=130),'invalid grammar introduction chapter '+f.id);
  const signature=f.id+'|'+JSON.stringify(f.conjugations||null);
  must(!featureSignatures.has(signature),'duplicate grammar signature '+signature);
  featureSignatures.add(signature);
 }
 // Only genuine owner/Latinist signed sample pattern tables may certify
 // generated regular morphology. Tests may inject SYNTHETIC maps in memory.
 const reviewPath=path.join(root,'tests/fixtures/paradigms/REGULAR_PATTERN_SAMPLES.json');
 const samples=opts.patternSamples||JSON.parse(fs.readFileSync(reviewPath,'utf8'));
 const approvedPatterns={};
 for(const item of samples.approved_patterns||[]){
  if(item&&typeof item.pattern==='string'&&item.reviewed===true&&
   typeof item.approved_by==='string'&&item.approved_by.trim()&&validDate(item.approved_at)){
   approvedPatterns[item.pattern]={reviewed:true,reviewer:item.approved_by,reviewed_at:item.approved_at};
  }
 }
 function reviewedForm(t,lex){
  if(lex.forms_policy==='regular'){
   const parts=typeof lex.principal_parts==='string'?lex.principal_parts.split(/[,;]/).map(x=>x.trim()):[];
   const withStem={...lex,genitive:lex.genitive||parts[1]||null};
   try{
    const normalized=normalizeMorph({...t,pos:lex.pos,lemma:lex.head,conjugation:lex.conjugation},lex);
    const outcome=checkForm({t:t.t,morph:normalized},withStem,approvedPatterns);
    return outcome.ok?null:(outcome.reason==='pattern_not_reviewed'?
      'no owner-approved paradigm table for '+outcome.pattern:'no matching generated surface+morphology for '+t.t+' ('+outcome.reason+')');
   }catch(e){return 'regular paradigm error for '+t.t+': '+e.message}
  }
  // Explicit signed forms are required for irregular/defective or manually
  // checked legacy lexemes. A same-spelling different macron never passes.
  let mk;try{mk=morphKey(t.morph)}catch(e){return e.message}
  return Array.isArray(lex.forms)&&lex.forms.some(f=>f&&f.surface===t.t&&f.reviewed===true&&typeof f.morph==='string'&&morphKey(f.morph)===mk)
   ?null:'no reviewed surface+morphology for '+t.t+' ('+lex.id+'); macrons must match exactly';
 }
 const sources=opts.lessons||listing(path.join(root,'lessons')).map(p=>({path:path.relative(root,p).split(path.sep).join('/'),data:JSON.parse(fs.readFileSync(p,'utf8'))}));
 const seen=new Map(),retiredSet=new Set(retired.ids);const legacy=[],course=[],errors=[],warnings=[];
 const html=opts.legacyHTML===undefined?(fs.existsSync(path.join(root,'index.html'))?readLegacySource(root):null):opts.legacyHTML;
 const original=html?extractLessons(html):[],originalCloze=html?extractArray(html,'const guidedCloze=','\n];\n// Contextual hints'):[];
 for(const src of sources){const l=src.data,where=src.path||'fixture';must(l.schema==='tablinum-lesson-v1',`${where}: schema invalid`);addId(l.id,where,seen,retiredSet);
  if(l.legacy){
   must(/^legacy-ch\d{2}$/.test(l.id)&&l.status==='legacy_unreviewed',`${where}: invalid legacy status/id`);
   must(Number.isInteger(l.original_zero_based_index)&&l.original_zero_based_index>=0&&l.original_zero_based_index<original.length,`${where}: legacy source index invalid`);
   const i=l.original_zero_based_index,old=original[i];
   must(l.id===`legacy-ch${String(i+1).padStart(2,'0')}`,`${where}: legacy ID drift`);
   must(JSON.stringify(l.legacy_source)===JSON.stringify(old)&&fnv32(JSON.stringify(old))===l.legacy_source_fingerprint_fnv32,`${where}: original legacy lesson changed`);
   must(JSON.stringify(l.cloze_source)===JSON.stringify(originalCloze[i]),`${where}: original legacy cloze changed`);
   must(Array.isArray(l.sentences)&&l.sentences.length===old.sent.length,`${where}: legacy sentence count changed`);
   for(const [j,s] of l.sentences.entries()){
    addId(s.id,where,seen,retiredSet);must(s.id===`${l.id}-s${String(j+1).padStart(3,'0')}`,`${where}: legacy sentence ID moved`);
    must(s.text_la===old.sent[j][0]&&s.en===old.sent[j][1],`${where}/${s.id}: original Latin or English changed`);
    checkTokens(s,where+'/'+s.id,{legacy:true});
   }
   must(Array.isArray(l.questions)&&l.questions.length===old.q.length,`${where}: question count changed`);
   for(const [j,q]of l.questions.entries()){addId(q.id,where,seen,retiredSet);must(q.id===`${l.id}-q${String(j+1).padStart(3,'0')}`&&JSON.stringify(q.legacy_source)===JSON.stringify(old.q[j]),`${where}: original exercise changed`)}
   legacy.push({source:src,lesson:l});continue;
  }
  must(courseStatus(l),`${where}: invalid lesson status`);
  must(Number.isInteger(l.chapter)&&l.chapter>=1&&l.chapter<=130,`${where}: invalid chapter`);
  const chapterPlan=plan.chapters[l.chapter-1];must(chapterPlan&&l.id===expectedCourseId(l.chapter),`${where}: course ID does not match chapter/book`);
  must(l.book===chapterPlan.book&&l.is_review===chapterPlan.review,`${where}: book/review conflicts with syllabus`);
  must(l.title===chapterPlan.title,`${where}: title drift from plan`);
  must(l.budget_ref===`curriculum/vocabulary-budgets-130.json#${l.chapter}`,`${where}: invalid budget reference`);
  must(Array.isArray(l.new_lexemes_declared)&&new Set(l.new_lexemes_declared).size===l.new_lexemes_declared.length,`${where}: duplicate new_lexemes_declared`);
  must(Array.isArray(l.grammar_new)&&new Set(l.grammar_new).size===l.grammar_new.length,`${where}: duplicate grammar_new`);
  must(Array.isArray(l.segments)&&(l.segments.length>0||l.status==='draft'),`${where}: missing reading segments`);
  const sentenceIds=[];
  for(const seg of l.segments){addId(seg.id,where,seen,retiredSet);must(seg.id.startsWith(l.id+'-l'),`${where}: wrong segment ID prefix`);
   must(Array.isArray(seg.sentences)&&(seg.sentences.length>0||l.status==='draft'),`${where}/${seg.id}: empty segment`);
   for(const s of seg.sentences){addId(s.id,where,seen,retiredSet);must(s.id.startsWith(l.id+'-s'),`${where}: wrong sentence ID prefix`);
    checkTokens(s,where+'/'+s.id);sentenceIds.push(s.id);
    if(l.status==='approved')for(const t of s.tokens){
      if(!t.lx){
       const hasMargin=Array.isArray(s.margin)&&s.margin.some(m=>Number.isInteger(m.token)&&m.token===s.tokens.indexOf(t)&&typeof m.gloss_la==='string'&&m.gloss_la.trim());
       if(!t.gloss_only||!hasMargin)errors.push(`${where}/${s.id}: unknown reading lexeme for ${t.t}; gloss_only requires a real Latin marginal annotation`);
       continue;
      }
      const lex=regMap.get(t.lx);
      if(!lex||lex.status!=='approved'){errors.push(`${where}/${s.id}: unapproved lexeme ${t.lx} (token ${t.t})`);continue}
      if(t.proper_name&&lex.pos!=='proper_name')errors.push(`${where}/${s.id}: ${t.lx} incorrectly marked as a proper name`);
      const formProblem=reviewedForm(t,lex);
      if(formProblem)errors.push(where+'/'+s.id+': '+formProblem);

     }
   }
  }
  for(const type of ['exercises','speaking'])for(const v of (l[type]||[])){
   addId(v.id,where,seen,retiredSet);must(v.id.startsWith(l.id+(type==='exercises'?'-q':'-sp')),`${where}: wrong ${type} ID`);
  }
  if(l.status==='approved'){
   const latin=l.review?.latin,ped=l.review?.pedagogy;
   must(latin&&validDate(latin.at)&&latin.by&&['owner','latinist'].includes(latin.tier),`${where}: approved chapter requires genuine signed Latin review with tier`);
   must(ped&&validDate(ped.at)&&ped.by,`${where}: approved chapter requires signed pedagogy review`);
  }
  if(l.status==='draft'&&l.drafted_by==='claude-draft-2026-11-05'&&l.chapter<=8){
   const issues=checkPilot(l,grammar);
   for(const issue of issues)errors.push(where+': '+issue);
  }
  course.push({source:src,lesson:l,plan:chapterPlan});
 }
 course.sort((a,b)=>a.lesson.chapter-b.lesson.chapter);
 for(let i=1;i<course.length;i++)must(course[i].lesson.chapter!==course[i-1].lesson.chapter,'Duplicate course chapter '+course[i].lesson.chapter);
 const approved=course.filter(x=>x.lesson.status==='approved');const published=new Set(approved.map(x=>x.lesson.chapter));
 const known=new Map(),introductions=[],readingCounts=new Map(),allCounts=new Map(),coverage=[],grammarOut=[];
 for(const {lesson:l,source:src,plan:chapterPlan} of approved){
   // Never treat approval of a later chapter as a missing earlier chapter's lexical evidence.
   if(l.chapter>1&&[...Array(l.chapter-1)].some((_,i)=>!published.has(i+1)))errors.push(`${l.id}: prior course chapter(s) not approved; cannot certify first introductions`);
   const newHere=new Set(),counter=new Map();
   for(const seg of l.segments)for(const s of seg.sentences)for(const t of s.tokens){
    if(!t.lx||t.gloss_only)continue;
    const lex=regMap.get(t.lx);if(!lex||lex.status!=='approved'||lex.pos==='proper_name')continue;
    counter.set(t.lx,(counter.get(t.lx)||0)+1);
    if(!known.has(t.lx)){
     known.set(t.lx,l.chapter);newHere.add(t.lx);
     const provenance=lex.sources[0];
     introductions.push({lexeme_id:lex.id,headword:lex.head,english_gloss:lex.senses[0].gloss_en,first_chapter:l.chapter,lesson_path:src.path,sentence_id:s.id,
       source_reference:`${provenance.source_id}#${provenance.locator} (${provenance.license_id})`,reviewed_by:lex.reviewed_by,reviewed_at:lex.reviewed_at,part_of_speech:lex.pos,
       review_tier:lex.review_tier,...(lex.review_tier==='owner'?{drafted_by:lex.drafted_by}:{}),derived_from_hash:sha(json(l))});
    }
   }
   readingCounts.set(l.chapter,counter);
   const allCounter=new Map(counter);
   for(const ex of (l.exercises||[])){
    if(typeof ex.prompt_la!=="string"||!Array.isArray(ex.tokens))errors.push(`${l.id}/${ex.id}: approved exercise needs prompt_la plus annotated tokens`);
    else{
     checkTokens({text_la:ex.prompt_la,tokens:ex.tokens},`${l.id}/${ex.id}`);
     for(const t of ex.tokens){
      if(!t.lx||!known.has(t.lx)){errors.push(`${l.id}/${ex.id}: exercise-only or unapproved word ${t.t} (${t.lx||'untagged'}) is not a reading introduction`);continue}
      const lex=regMap.get(t.lx);
      const formProblem=reviewedForm(t,lex);
      if(formProblem)errors.push(l.id+'/'+ex.id+': exercise '+formProblem);
      allCounter.set(t.lx,(allCounter.get(t.lx)||0)+1);
     }
    }
   }
   allCounts.set(l.chapter,allCounter);
   const declared=new Set(l.new_lexemes_declared);
   if(declared.size!==newHere.size||[...newHere].some(v=>!declared.has(v)))errors.push(`${l.id}: new_lexemes_declared ${[...declared].join(',')} differs from first reading occurrences ${[...newHere].join(',')}`);
   if(newHere.size>chapterPlan.budget_new_lemmas)errors.push(`${l.id}: ${newHere.size} new words exceeds budget ${chapterPlan.budget_new_lemmas}`);
   if(l.is_review&&newHere.size)errors.push(`${l.id}: review chapter introduces words`);
   if(l.is_review&&l.grammar_new.length)errors.push(`${l.id}: review chapter cannot introduce new grammar`);
   if(newHere.size<chapterPlan.budget_new_lemmas*.8&&!l.review)warnings.push(`${l.id}: ${newHere.size} new lexemes below 80% of budget ${chapterPlan.budget_new_lemmas}`);
   coverage.push({chapter:l.chapter,id:l.id,...checkCoverage(l,newHere,errors,warnings)});
   grammarOut.push({chapter:l.chapter,id:l.id,...checkGrammar(l,grammar.features,errors,regMap)});
 }
 const recurrence=recurrenceReport(introductions,readingCounts,allCounts,plan,published);
 for(const r of recurrence)for(const p of r.problems)errors.push(`${r.lexeme_id}: recurrence ${p}`);
 const catalog=[...legacy,...approved].map(({source,lesson:l})=>({id:l.id,chapter:l.legacy?null:l.chapter,title:l.title,legacy:!!l.legacy,review_tier:l.legacy?'unreviewed':l.review.latin.tier,source_hash:sha(json(l)),script:`content/${l.legacy?'legacy/'+`ch${String(l.original_zero_based_index+1).padStart(2,'0')}`:`b0${l.book}/c${String(l.chapter).padStart(3,'0')}`}.js`})).sort((a,b)=>a.id.localeCompare(b.id));
 const sourceHash=sha(json({catalog,registry_sha:sha(json(reg)),grammar_sha:sha(json(grammar.features))}));
 const ledger={...oldLedger,generated_by:'scripts/compile-content.cjs',generated_from_hash:sourceHash,introduced_lexemes:introductions};
 // Stable deterministic strings for all generated files; no runtime state changes.
 const outputs=new Map();
 for(const {lesson:l} of legacy)outputs.set(`content/legacy/ch${String(l.original_zero_based_index+1).padStart(2,'0')}.js`,outScript(l.id,l));
 for(const {lesson:l} of approved)outputs.set(`content/b0${l.book}/c${String(l.chapter).padStart(3,'0')}.js`,outScript(l.id,l));
 outputs.set('content/catalogue.js',outScript('catalogue',{schema:'tablinum-content-catalogue-v1',generated_from_hash:sourceHash,entries:catalog}));
 outputs.set('content/lexicon.js',outScript('lexicon',{schema:'tablinum-content-lexicon-v1',source_hash:sha(json(reg)),lexemes:reg.lexemes.filter(e=>e.status==='approved')}));
 outputs.set('curriculum/vocabulary-introductions-130.json',json(ledger));
 const coverHead='# Phase 2 — approved reading coverage\n\nUnapproved drafts and eight legacy chapters are excluded. No authored chapter is certified merely from a budget.\n\n| Chapter | Running tokens | Mean sentence length | New-token density by segment |\n|---:|---:|---:|---|\n';
 outputs.set('reports/coverage-b01.md',coverHead+(coverage.map(c=>`| ${c.chapter} | ${c.reading_tokens} | ${c.mean_sentence_length} | ${c.segments.map(s=>`${s.segment}: ${s.new_density_percent}%`).join('; ')} |`).join('\n')||'| — | 0 | — | No approved lessons yet |')+'\n');
 outputs.set('reports/recurrence.md','# Phase 2 — lexeme recurrence\n\nPENDING means later chapters are unwritten or unapproved; it is not a passing result.\n\n| Lexeme | Chapter | In chapter | Next 3 | Review hit | Status | Issues |\n|---|---:|---:|---:|---:|---|---|\n'+(recurrence.map(r=>`| ${r.lexeme_id} | ${r.chapter} | ${r.in_chapter} | ${r.next_three} | ${r.review_occurrences} | ${r.followup_status} | ${r.problems.join('; ')||'—'} |`).join('\n')||'| — | — | — | — | — | NO CERTIFIED INTRODUCTIONS | — |')+'\n');
 outputs.set('reports/grammar-violations.md','# Phase 2 — grammar feature gate\n\nPartial rule map; taggers and unlisted syntax have not been independently checked. Approved lessons must carry explicit tags.\n\n'+(grammarOut.map(g=>`- ${g.id}: ${g.preview_sentences} previews; new-feature exposures ${JSON.stringify(g.grammar_new_exposures)}`).join('\n')||'No approved new-course lessons.')+'\n');
 if(errors.length)throw Error('CONTENT COMPILER FAILED:\n- '+errors.join('\n- '));
 return {outputs,stats:{legacy:legacy.length,draft:course.length-approved.length,approved:approved.length,introduced:introductions.length,warnings,generated_from_hash:sourceHash}};
}
function writeOrCheck(result,root,check){
 const outputs=result.outputs,generatedHeader='/* Generated by scripts/compile-content.cjs. Do not edit. */';
 for(const sub of ['legacy','b01','b02','b03']){
  const folder=path.join(root,'content',sub);
  if(!fs.existsSync(folder))continue;
  for(const name of fs.readdirSync(folder).filter(n=>n.endsWith('.js'))){
   const dest=path.join(folder,name),rel=path.relative(root,dest).split(path.sep).join('/');
   if(outputs.has(rel))continue;
   const source=fs.readFileSync(dest,'utf8');
   if(!source.startsWith(generatedHeader))throw Error(`Unmanaged content script; refusing to remove: ${rel}`);
   if(check)throw Error(`Obsolete generated content script: ${rel}`);
   fs.unlinkSync(dest);
  }
 }
 for(const [rel,value] of outputs){
  const dest=path.join(root,rel);
  if(check){if(!fs.existsSync(dest)||fs.readFileSync(dest,'utf8')!==value)throw Error(`Generated output stale or missing: ${rel}; run node scripts/compile-content.cjs`)}
  else{fs.mkdirSync(path.dirname(dest),{recursive:true});fs.writeFileSync(dest,value)}
 }
}
function main(){const check=process.argv.includes('--check');const r=compile();writeOrCheck(r,ROOT,check);console.log(`PASS Phase 2 ${check?'checked':'compiled'}: ${r.stats.legacy} preserved legacy, ${r.stats.draft} draft, ${r.stats.approved} approved new lessons, ${r.stats.introduced} certified lexical introductions.`);for(const w of r.stats.warnings)console.log('WARNING '+w)}
if(require.main===module){try{main()}catch(e){console.error(e.message);process.exitCode=1}}
module.exports={compile,writeOrCheck};
