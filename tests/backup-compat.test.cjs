"use strict";
const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict");
const {createHarness}=require("./helpers/legacy-app-harness.cjs");
const read=p=>JSON.parse(fs.readFileSync(path.join(__dirname,"fixtures",p),"utf8"));
const mid=read("v4/midcourse.json"),caps=read("v4/at-caps.json"),v2=read("backups/v2-envelope.json");
const raw=JSON.stringify(mid),h=createHarness(raw);
assert.equal(h.raw,raw,"v4 original must remain byte-identical after startup");
assert(h.savedKeys.includes("tablinum-v4-snapshot"));
assert(h.savedKeys.includes("tablinum-state-v5"));
assert.equal(h.state().ch,3);
assert.equal(h.state().sel,3);
assert.deepEqual(JSON.parse(JSON.stringify(h.state().notes)),mid.notes);
assert.equal(Object.keys(h.state().vocab).length,30);
assert.equal(Object.keys(h.v5().deck.legacyCards).length,30,"No invented lexeme approvals");
const full=createHarness(JSON.stringify(caps));
assert.equal(Object.keys(full.state().notes).length,120,"All 120 notes must survive");
assert.equal(full.state().notes["119"],"record 119");
assert.equal(full.raw,JSON.stringify(caps),"At-caps v4 original unchanged");
const largeText={...mid,custom:"L".repeat(24000),answers:{...mid.answers,"0:0":"V".repeat(780)},notes:{...caps.notes}};
const largeHarness=createHarness(JSON.stringify(largeText));
largeHarness.click({tab:"progress"});
assert.equal(largeHarness.v5().custom.text.length,24000,"Previously saved imported text must not be truncated during migration or subsequent saves");
assert.equal(largeHarness.v5().questions["legacy-ch01-q001"].answer.length,780,"Previously saved long responses must not be truncated");
assert.equal(Object.keys(largeHarness.state().notes).length,120);
const source=h.state();h.click({tab:"progress"});h.click({action:"export"});
const first=h.downloads.at(-1);
assert(/^tablinum-backup-\d{4}-\d\d-\d\d\.json$/.test(first.filename));
const envelope=JSON.parse(first.content);
assert.equal(envelope.app,"tablinum");assert.equal(envelope.version,5);
assert.equal(envelope.state.version,5);
assert.equal(envelope.state.ui.chapterId,"legacy-ch04");
assert.equal(envelope.state.backup.lastExportAt!==null,true);
const restored=createHarness("{}");
restored.change("restoreFile",first.content);
assert.equal(restored.v5().ui.chapterId,"legacy-ch04");
assert.equal(Object.keys(restored.v5().deck.legacyCards).length,30);
assert.equal(restored.raw,"{}","Restore must not touch original v4 key");
restored.click({tab:"progress"});restored.click({action:"export"});
const second=JSON.parse(restored.downloads.at(-1).content);
delete envelope.exportedAt;delete second.exportedAt;
assert.deepEqual(second,envelope,"v5 export/restore/export stable apart from exportedAt");
const legacy=createHarness("{}");legacy.change("restoreFile",JSON.stringify(v2));
assert.equal(legacy.v5().ui.chapterId,"legacy-ch02");
assert.equal(legacy.v5().questions["legacy-ch02-q001"].correct,true);
assert.equal(legacy.v5().chapters["legacy-ch02"].notes,"Old backup from v0.2.");
assert.equal(Object.keys(legacy.v5().deck.legacyCards).length,1);
const oldV4=createHarness("{}");oldV4.change("restoreFile",JSON.stringify({app:"tablinum",version:4,state:mid}));
assert.equal(oldV4.v5().ui.chapterId,"legacy-ch04");
assert.equal(Object.keys(oldV4.v5().deck.legacyCards).length,30);
assert.equal(oldV4.raw,"{}");
console.log("PASS Phase3c: v2/v4/v5 backup restores, 120 notes, 30 cards, original v4 immutable and v5 roundtrip.");
